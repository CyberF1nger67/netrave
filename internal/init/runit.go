package init

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"netrave/internal/platform"
)

// Runit uses /etc/sv/<name> and a service symlink. Void uses /var/service;
// Alpine traditionally uses /etc/service, so the adapter picks an existing
// service root.
type Runit struct{ Base }

func (r *Runit) Kind() platform.InitKind { return platform.InitRunit }

func (r *Runit) serviceDir() string {
	return filepath.Join("/etc/sv", r.Config.Name)
}

func (r *Runit) linkRoot() string {
	for _, path := range []string{"/var/service", "/etc/service"} {
		if info, err := os.Stat(r.path(path)); err == nil && info.IsDir() {
			return path
		}
	}
	return "/etc/service"
}

func (r *Runit) UnitPath() string { return r.serviceDir() }

func (r *Runit) Install(cfg ServiceConfig) error {
	run := fmt.Sprintf(`#!/bin/sh
# Generated by netrave installer.
exec 2>&1
exec %s daemon --config %s --foreground
`, cfg.Binary, cfg.ConfigFile)
	finish := `#!/bin/sh
# Keep the supervisor alive; the daemon handles its own restart policy.
exit 0
`
	if err := r.writeFile(filepath.Join(r.serviceDir(), "run"), 0o755, run); err != nil {
		return err
	}
	return r.writeFile(filepath.Join(r.serviceDir(), "finish"), 0o755, finish)
}

func (r *Runit) linkPath() string {
	return filepath.Join(r.linkRoot(), r.Config.Name)
}

func (r *Runit) Enable() error {
	full := r.path(r.linkPath())
	if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
		return err
	}
	if _, err := os.Stat(full); err == nil {
		return nil
	}
	return os.Symlink(r.path(r.serviceDir()), full)
}

func (r *Runit) Disable() error {
	err := os.Remove(r.path(r.linkPath()))
	if os.IsNotExist(err) {
		return nil
	}
	return err
}

func (r *Runit) Remove() error {
	_ = r.Disable()
	_ = r.Stop()
	if err := os.RemoveAll(r.path(r.serviceDir())); err != nil {
		return err
	}
	return nil
}

func (r *Runit) Run(args ...string) error { return r.run("sv", args...) }
func (r *Runit) Start() error             { return r.Run("start", r.Config.Name) }
func (r *Runit) Stop() error              { return r.Run("stop", r.Config.Name) }
func (r *Runit) Restart() error           { return r.Run("restart", r.Config.Name) }

func (r *Runit) Status() (string, error) {
	ctx, cancel := contextWithTimeout()
	defer cancel()
	output, err := r.Runner.Run(ctx, "sv", "status", r.Config.Name)
	if err != nil {
		return strings.TrimSpace(output), nil
	}
	return strings.TrimSpace(output), nil
}

func (r *Runit) Logs(lines int) (string, error) { return tailFile(r.Config.LogFile, lines) }
